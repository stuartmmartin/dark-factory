"""Render the graph as committed, deterministic artifacts under docs/generated/."""

from __future__ import annotations

import ast
import json
from pathlib import Path, PurePosixPath

from sb_graph.graph import Graph
from sb_graph.imports import parse_file

GENERATED_DIR = PurePosixPath("docs/generated")
SCHEMA_VERSION = 2  # 2: test_depends_on + test_edges
GENERATED_MARKER = "Generated by `make graph`. Do not edit."
HEADER = f"<!-- {GENERATED_MARKER} -->"
MAX_SIGNATURE = 120


def render_json(graph: Graph) -> str:
    data: dict[str, object] = {
        "_generated": GENERATED_MARKER,
        "schema_version": SCHEMA_VERSION,
        "members": [
            {
                "name": m.name,
                "import_name": m.import_name,
                "path": str(m.path),
                "kind": m.kind,
                "language": m.language,
                "depends_on": list(m.declared),
                "test_depends_on": list(m.test_declared),
            }
            for m in graph.members
        ],
        "edges": [list(edge) for edge in graph.edges],
        "test_edges": [list(edge) for edge in graph.test_edges],
    }
    return json.dumps(data, indent=2, sort_keys=True) + "\n"


def _node_id(name: str) -> str:
    return name.replace("-", "_")


def render_mermaid(graph: Graph) -> str:
    lines = [HEADER, "# Build graph", "", "```mermaid", "flowchart LR"]
    lines += [f'  {_node_id(m.name)}["{m.name}<br/>{m.kind}"]' for m in graph.members]
    lines += [f"  {_node_id(a)} --> {_node_id(b)}" for a, b in graph.edges]
    lines += [f"  {_node_id(a)} -.-> {_node_id(b)}" for a, b in graph.test_edges]
    lines += ["```", ""]
    return "\n".join(lines)


def _dunder_all(tree: ast.Module) -> set[str] | None:
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and any(isinstance(t, ast.Name) and t.id == "__all__" for t in node.targets)
            and isinstance(node.value, (ast.List, ast.Tuple))
        ):
            return {
                e.value
                for e in node.value.elts
                if isinstance(e, ast.Constant) and isinstance(e.value, str)
            }
    return None


def _signature(node: ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef) -> str:
    if isinstance(node, ast.ClassDef):
        bases = ", ".join(ast.unparse(base) for base in node.bases)
        text = f"class {node.name}({bases})" if bases else f"class {node.name}"
    else:
        prefix = "async def" if isinstance(node, ast.AsyncFunctionDef) else "def"
        returns = f" -> {ast.unparse(node.returns)}" if node.returns else ""
        text = f"{prefix} {node.name}({ast.unparse(node.args)}){returns}"
    return text if len(text) <= MAX_SIGNATURE else text[: MAX_SIGNATURE - 3] + "..."


def public_symbols(tree: ast.Module) -> list[str]:
    exported = _dunder_all(tree)
    symbols: list[str] = []
    for node in tree.body:
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            continue
        if node.name.startswith("_") or (exported is not None and node.name not in exported):
            continue
        symbols.append(_signature(node))
    return symbols


def _module_name(src: Path, file: Path) -> str:
    parts = file.relative_to(src).with_suffix("").parts
    return ".".join(parts[:-1] if parts[-1] == "__init__" else parts)


def render_module_index(root: Path, graph: Graph) -> str:
    lines = [
        HEADER,
        "# Module index",
        "",
        "Public API of every workspace member. Read this before opening files.",
        "",
    ]
    for member in graph.members:
        lines += [f"## {member.name} (`{member.path}`, {member.kind})", ""]
        if member.declared:
            lines += [f"Depends on: {', '.join(member.declared)}", ""]
        if member.test_declared:
            lines += [f"Test depends on: {', '.join(member.test_declared)}", ""]
        src = root / member.path / "src"
        for file in sorted(src.rglob("*.py")) if src.is_dir() else []:
            tree = parse_file(root, file)
            docstring = ast.get_docstring(tree)
            summary = docstring.strip().splitlines()[0] if docstring else "(no docstring)"
            lines.append(f"- `{_module_name(src, file)}` — {summary}")
            lines += [f"  - `{symbol}`" for symbol in public_symbols(tree)]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def generated_files(root: Path, graph: Graph) -> dict[PurePosixPath, str]:
    return {
        GENERATED_DIR / "build-graph.json": render_json(graph),
        GENERATED_DIR / "build-graph.md": render_mermaid(graph),
        GENERATED_DIR / "module-index.md": render_module_index(root, graph),
    }
